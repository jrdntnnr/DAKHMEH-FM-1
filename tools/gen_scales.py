"""Regenerate the checked-in scale table; --check verifies it without writes."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

# Rows 0..40 are saved in projects and presets by ID. CUSTOM (40) reads its
# keys and trims from the track; factory rows are appended after it.
SCALE_CUSTOM_ID = 40
LEGACY_SHA256 = "dbac2d1b8800f4fcebcf46441d0039c5f54cd2be6171d1d35b1624b860d961b4"


def generate():
    rows = json.loads((ROOT / "assets/scales.json").read_text())
    if not 16 <= len(rows) <= 128:
        raise ValueError("scale count must be 16..128")
    # ED_DESC has a 600-byte SysEx buffer. Never silently truncate a catalog.
    if 32 + sum(len(r["name"]) + 1 for r in rows) > 590:
        raise ValueError("scale names exceed the editor descriptor budget")
    if len({r["name"] for r in rows}) != len(rows):
        raise ValueError("scale names must be unique")

    # Frozen IDs: any edit, insertion or removal before CUSTOM breaks saved music
    legacy = json.dumps([{k: r[k] for k in ("name", "keys", "offsets")} for r in rows[:SCALE_CUSTOM_ID + 1]],
                        sort_keys=True).encode()
    if hashlib.sha256(legacy).hexdigest() != LEGACY_SHA256:
        raise ValueError("scales 0..40 are frozen; append new scales after CUSTOM")
    for row in rows:
        keys, cents = row["keys"], row["offsets"]
        if not keys or keys != sorted(set(keys)) or keys[0] != 0 or keys[-1] > 11:
            raise ValueError("keys must be sorted, unique, include zero and fit an octave")
        if len(cents) != 12 or any(type(c) is not int or not -63 <= c <= 63 for c in cents):
            raise ValueError("each scale needs twelve integral cent offsets in -63..63")
        if not row["name"].isascii() or len(row["name"]) > 8:
            raise ValueError("scale names must fit eight ASCII characters")
        if row.get("names", "western") not in ("western", "arabic"):
            raise ValueError("names must be western or arabic")
    text = "/* SPDX-License-Identifier: GPL-3.0-only */\n"
    text += "/* Generated by tools/gen_scales.py from assets/scales.json. IDs are append-only. */\n"
    text += "enum { SCALE_CUSTOM_ID = %d };\n" % SCALE_CUSTOM_ID
    text += "static const char *const N_SCALE[] = {" + ", ".join(json.dumps(r["name"]) for r in rows) + "};\n"
    text += "static const uint16_t SCALE_MASK[] = {" + ", ".join(hex(sum(1 << k for k in r["keys"])) for r in rows) + "};\n"
    text += "static const int8_t SCALE_CENTS[][12] = {\n"
    text += "".join("    {" + ", ".join(map(str, r["offsets"])) + "}, /* " + r["name"] + " */\n" for r in rows)
    text += "};\n"
    # GHOULBOX desert: the maqamat ("names": "arabic"), a bit per scale: the header names a held note the
    # Arabic way (ui_input.c names_of)
    bits = [0] * ((len(rows) + 7) // 8)
    for i, r in enumerate(rows):
        if r.get("names") == "arabic":
            bits[i // 8] |= 1 << (i % 8)
    text += "static const uint8_t SCALE_ARABIC[] = {" + ", ".join(hex(b) for b in bits) + "};\n"
    text += "static int scale_arabic(uint32_t s) { return s / 8u < sizeof SCALE_ARABIC && (SCALE_ARABIC[s / 8u] >> (s % 8u)) & 1u; }\n"
    return text


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "firmware/src/scales.h"
    text = generate()
    if args.check:
        if target.read_text() != text:
            raise SystemExit("scales.h is stale; run python3 tools/gen_scales.py")
    else:
        target.write_text(text)
