"""Build deterministic SARDAB/Grimm v2 multisample banks and embedded factory data.
Continuous ADPCM stream: existing decoder/seek RAM is reused for all zones.
Input WAVs are already calibrated SARDAB assets (see source manifests).
"""
from pathlib import Path
import json,struct,zlib,hashlib
import sampleio as sio
from gen_samples import carray
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'assets/desert'
CAP=73216

def build(bank):
    zones=[];pcm=[]
    files=bank['files']
    # Tar needs ~2.2% shorter tails to fit four roots in Grimm's 72 KiB slot.
    cap=(CAP*2)//len(files)
    roots=[f['root'] for f in files]
    for f,(lo,hi) in zip(files,sio.key_split(roots)):
        rate,s,_=sio.read_wav(OUT/f['file'])
        assert rate==22050,rate
        s=s[:min(len(s),cap)]
        fade=min(441,len(s))
        for j in range(fade):s[-fade+j]=int(s[-fade+j]*(fade-1-j)/max(1,fade-1))
        zones.append((len(pcm),len(s),0,0,f['root']*16,lo,hi,0))
        pcm+=s
    data,_=sio.ima_encode(pcm,0)
    assert len(data)<=CAP
    h=bytearray(480)
    struct.pack_into('<IHBB8sII',h,0,0x504D5347,2,len(zones),0,bank['name'].encode()[:8].ljust(8,b'\0'),len(data),zlib.crc32(data))
    struct.pack_into('<5Ih',h,32,0,len(pcm),0,len(pcm)-1,32768,roots[0]*16)
    for i,z in enumerate(zones):struct.pack_into('<4Ih3B3x',h,64+24*i,*z)
    struct.pack_into('<I',h,28,zlib.crc32(h[32:],zlib.crc32(h[:28])))
    return bytes(h),bytes(data),zones

def main():
    banks=json.loads((OUT/'source-banks.json').read_text());out=['/* Generated by tools/build_desert_banks.py. See assets/desert source manifests for credits. */','#define SMP_FACT_N 4u'];manifest=[]
    for i,b in enumerate(banks):
        h,d,z=build(b);stem=b['name'].lower().replace(' ','-')
        (OUT/f'{stem}.hdr').write_bytes(h);(OUT/f'{stem}.bin').write_bytes(d)
        out += [carray(f'SMP_FH{i}',h),carray(f'SMP_FD{i}',d)]
        manifest.append(dict(name=b['name'],slot=i+1,header=f'{stem}.hdr',data=f'{stem}.bin',bytes=len(d),zones=[dict(root=x[4]//16,lo=x[5],hi=x[6],frames=x[1]) for x in z],sha256=hashlib.sha256(h+d).hexdigest()))
        print(f'{b["name"]}: {len(z)} zones, {len(d)}/{CAP} bytes')
    out += ['static const uint8_t *const SMP_FACT_HDR[SMP_FACT_N] = {'+', '.join(f'SMP_FH{k}' for k in range(4))+'};','static const uint8_t *const SMP_FACT_DATA[SMP_FACT_N] = {'+', '.join(f'SMP_FD{k}' for k in range(4))+'};','static const uint32_t SMP_FACT_LEN[SMP_FACT_N] = {'+', '.join(f'sizeof SMP_FD{k}' for k in range(4))+'};']
    (ROOT/'firmware/gen/grimm_samples.h').write_text('\n'.join(out)+'\n');(OUT/'banks.json').write_text(json.dumps(manifest,indent=2)+'\n')
if __name__=='__main__':main()
