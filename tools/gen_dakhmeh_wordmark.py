"""Shape دخمه with bundled Reem Kufi; emit the device's one-bit wordmark.
Optional regeneration: Pillow, fontTools[woff], HarfBuzz hb-view.
"""
from pathlib import Path
import hashlib, subprocess, tempfile
from PIL import Image
from fontTools.ttLib import TTFont
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'assets/fonts/reem-kufi.woff2'
with tempfile.TemporaryDirectory() as tmp:
    tmp=Path(tmp);font=TTFont(source)
    assert all(ord(c) in font.getBestCmap() for c in 'دخمه')
    font.flavor=None; font.save(tmp/'font.ttf')
    subprocess.run(['hb-view',str(tmp/'font.ttf'),'دخمه','--direction=rtl','--language=fa','--script=arab','--shapers=ot','--variations=wght=600','--font-size=224','--foreground=ffffff','--background=000000','--margin=4',f'--output-file={tmp / "word.png"}'],check=True)
    im=Image.open(tmp/'word.png').convert('L');im=im.crop(im.getbbox())
    im=im.resize(((im.width+3)//4,(im.height+3)//4),Image.Resampling.LANCZOS).point(lambda v:255 if v>=112 else 0)
    im=im.crop(im.getbbox())
w,h=im.size; stride=(w+7)//8
assert w<=190 and h<=80,(w,h)
data=[sum((1<<(7-b)) for b in range(8) if x*8+b<w and im.getpixel((x*8+b,y))) for y in range(h) for x in range(stride)]
out=['/* SPDX-License-Identifier: OFL-1.1',' * دخمه — shaped RTL, Persian, Reem Kufi weight 600.',' * Generated by tools/gen_dakhmeh_wordmark.py; LICENSES/OFL-ReemKufi.txt.',f' * Source SHA256: {hashlib.sha256(source.read_bytes()).hexdigest()} */',f'#define DAKHMEH_WORD_W {w}',f'#define DAKHMEH_WORD_H {h}',f'#define DAKHMEH_WORD_STRIDE {stride}',f'static const uint8_t DAKHMEH_WORD[{len(data)}] = {{']
out += ['    '+', '.join(f'0x{v:02x}' for v in data[i:i+16])+',' for i in range(0,len(data),16)]
out += ['};','']
(ROOT/'firmware/gen/dakhmeh_wordmark.h').write_text('\n'.join(out))
im.save(ROOT/'assets/branding/dakhmeh-wordmark.png')
print(f'DAKHMEH wordmark: {w} x {h}, {len(data)} bytes')
